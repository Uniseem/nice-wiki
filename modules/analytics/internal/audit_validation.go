// ValidateAudit 核对固定生产者、可信主体与五分钟内的发生时间。
func ValidateAudit(ctx context.Context, op OperationContext, in ValidateAuditInput) (ValidateAuditResult, error) {
	origin := op.CallerService
	if in.VerifiedOrigin != "" {
		origin = in.VerifiedOrigin
	}
	producer, ok := auditActionProducer[in.Action]
	if !ok || producer != origin || (!in.Historical && in.ActorID != op.Actor.SubjectID) {
		return ValidateAuditResult{}, platform.NewError(platform.CodeForbidden, false, "审计生产者或主体不匹配")
	}
	if !platform.ValidIdentifier(in.AuditID) || !platform.ValidIdentifier(in.ResourceID) {
		return ValidateAuditResult{}, platform.NewError(platform.CodeValidation, false, "审计引用不合法")
	}
	if in.ResultCode != "SUCCESS" && in.ResultCode != "OK" {
		if _, ok := platform.ProblemHTTPStatus[in.ResultCode]; !ok {
			return ValidateAuditResult{}, platform.NewError(platform.CodeValidation, false, "审计结果未登记")
		}
	}
	at, err := time.Parse(time.RFC3339Nano, in.OccurredAt)
	if err != nil || (!in.Historical && time.Since(at) > 5*time.Minute) || time.Until(at) > 5*time.Minute {
		return ValidateAuditResult{}, platform.NewError(platform.CodeValidation, false, "审计发生时间超过允许窗口")
	}
	return ValidateAuditResult{Valid: true}, nil
}
