def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def dump(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def walk(node):
    if isinstance(node, dict):
        yield node
        for item in node.values():
            yield from walk(item)
    elif isinstance(node, list):
        for item in node:
            yield from walk(item)


def bundle_spec(spec_path, initial=None):
    """把外部$ref递归解析进components/schemas，返回自包含规格。

    引用相对其所在文件解析；同名不同内容按来源文件名加前缀。
    """
    spec_path = Path(spec_path).resolve()
    spec = load(spec_path) if initial is None else json.loads(json.dumps(initial, ensure_ascii=False))
    schemas = spec.setdefault("components", {}).setdefault("schemas", {})
    file_defs = {}
    final_names = {}
    used_finals = set(schemas)

    def defs_of(target):
        if target not in file_defs:
            file_defs[target] = load(target).get("$defs", {})
        return file_defs[target]

    def final_of(target, name):
        final = name
        if final in used_finals and schemas.get(final) is not None:
            content = defs_of(target).get(name)
            if schemas.get(final) == content and (target, name) not in final_names:
                pass
            elif final not in {v for v in final_names.values()}:
                final = target.stem + "_" + name
        return final

    def register(target, name):
        key = (target, name)
        if key in final_names:
            return final_names[key]
        defs = defs_of(target)
        if name not in defs:
            raise SystemExit(f"{spec_path}: 引用不存在 {target.name}#/{name}")
        final = name
        if final in used_finals:
            final = target.stem + "_" + name
        used_finals.add(final)
        final_names[key] = final
        schemas[final] = rewrite(defs[name], target)
        return final

    def rewrite(node, base):
        if isinstance(node, dict):
            ref = node.get("$ref")
            if isinstance(ref, str):
                if ref.startswith("#/components/"):
                    pass
                elif ref.startswith("#"):
                    name = ref.rstrip("/").split("/")[-1]
                    node["$ref"] = "#/components/schemas/" + register(base, name)
                elif not ref.startswith(("http://", "https://")):
                    file_part, _, pointer = ref.partition("#")
                    target = (base.parent / file_part).resolve()
                    name = pointer.rstrip("/").split("/")[-1]
                    node["$ref"] = "#/components/schemas/" + register(target, name)
            for key in list(node):
                rewrite(node[key], base)
        elif isinstance(node, list):
            for index, item in enumerate(node):
                rewrite(item, base)
        return node

    rewrite(spec, spec_path)
    return spec


def downgrade_to_30(spec):
    """把打包后的3.1规格确定性降级为oapi-codegen可读的3.0形态。

    只转换类型表达：可空anyOf/type数组改为nullable，const改为enum；
    不改变路径、operationId与权限标注。TS生成仍使用3.1原始规格。
    """
    result = json.loads(json.dumps(spec, ensure_ascii=False))
    result["openapi"] = "3.0.3"
    result.pop("jsonSchemaDialect", None)

    def is_null(entry):
        if not isinstance(entry, dict) or list(entry) not in (["type"], ["type", "description"]):
            return False
        kind = entry.get("type")
        return kind == "null" or (isinstance(kind, list) and set(kind) == {"null"})

    def walk(node):
        if isinstance(node, dict):
            for key in ("anyOf", "oneOf"):
                variants = node.get(key)
                if not isinstance(variants, list):
                    continue
                non_null = [v for v in variants if not is_null(v)]
                if len(non_null) < len(variants) and non_null:
                    node["nullable"] = True
                    node.pop(key)
                    if len(non_null) == 1:
                        entry = non_null[0]
                        if "$ref" in entry:
                            node["allOf"] = [{"$ref": entry["$ref"]}]
                            for name, value in entry.items():
                                if name != "$ref":
                                    node.setdefault(name, value)
                        else:
                            for name, value in entry.items():
                                node.setdefault(name, value)
                    else:
                        node[key] = non_null
            kind = node.get("type")
            if isinstance(kind, list):
                if "null" in kind:
                    node["nullable"] = True
                rest = [item for item in kind if item != "null"]
                if rest:
                    node["type"] = rest[0] if len(rest) == 1 else rest
                else:
                    node.pop("type")
            if "const" in node:
                node["enum"] = [node.pop("const")]
            for bound, base in (("exclusiveMinimum", "minimum"), ("exclusiveMaximum", "maximum")):
                limit = node.get(bound)
                if isinstance(limit, (int, float)) and not isinstance(limit, bool):
                    node[bound] = True
                    if node.get(base) is None:
                        node[base] = limit
            for value in list(node.values()):
                walk(value)
        elif isinstance(node, list):
            for item in node:
                walk(item)

    walk(result)
    return result


def operation_index(spec):
    """operationId -> (method, path, op)，同ID冲突时报错。"""
    index = {}
    for path, methods in spec.get("paths", {}).items():
        for method, op in methods.items():
            if method.lower() not in METHODS or not isinstance(op, dict):
                continue
            oid = op.get("operationId")
            if oid in index:
                raise SystemExit(f"重复operationId {oid}")
            index[oid] = (method.upper(), path, op)
    return index


def needed_operations(impl):
    """本域函数依赖中的跨域operation，按生产方分组并排序。"""
    needed = {}
    for file in impl.get("files", []):
        for fn in file.get("functions", []):
            for dep in fn.get("dependencies", []):
                producer, sep, oid = dep.partition(":")
                if sep and re.fullmatch(r"[a-z-]+", producer):
                    needed.setdefault(producer, set()).add(oid)
    return {p: sorted(ops) for p, ops in sorted(needed.items())}


def render_path_expression(path):
    """把/v1/jobs/{jobId}:x渲染为Go路径拼接表达式。"""
    expr = ""
    rest = path
    while True:
        match = re.search(r"\{([^}]+)\}", rest)
        if not match:
            return expr + json.dumps(rest)
        expr += json.dumps(rest[:match.start()]) + " + url.PathEscape(" + match.group(1) + ") + "
        rest = rest[match.end():]


def op_signature_parts(op):
    """返回(路径参数名列表, 是否需要幂等键)。"""
    params = []
    idempotency = False
    for parameter in op.get("parameters", []) or []:
        if parameter.get("in") == "path":
            params.append(parameter.get("name"))
        elif parameter.get("in") == "header" and parameter.get("name") == "Idempotency-Key" and parameter.get("required"):
            idempotency = True
    if not all(params):
        raise SystemExit("路径参数缺失")
    return params, idempotency


SSE_RETURNS = {"envelope": "(platform.EventStream, error)", "model": "(platform.ModelEventStream, error)"}


def render_operation(struct, producer, oid, method, path, op):
    """渲染客户端方法；查询和SSE游标按唯一OpenAPI参数传递。"""
    params, idempotency = op_signature_parts(op)
    sse = SSE_KIND.get(oid)
    if sse and sse not in SSE_RETURNS:
        raise SystemExit(f"未知SSE操作 {oid}")
    has_body = method in ("POST", "PUT", "PATCH")
    queries = [p for p in op.get("parameters", []) if p.get("in") == "query"]
    last_header = any(p.get("in") == "header" and p.get("name", "").lower() == "last-event-id" for p in op.get("parameters", []))
    name = oid[0].upper() + oid[1:]
    args = ["ctx context.Context"] + [f"{param} string" for param in params]
    if sse:
        args.append("lastEventId string")
    elif has_body:
        args.append("body any")
    if idempotency:
        args.append("idempotencyKey string")
    if queries:
        args.append("queries ...url.Values")
    returns = SSE_RETURNS[sse] if sse else "(json.RawMessage, error)"
    lines = [f"// {name} {method} {path}（{producer}:{oid}）。"]
    if queries:
        lines.append("// queries传递登记的查询参数；必填、类型和范围由拥有服务入口严格校验。")
    lines.append(f"func (c *{struct}Client) {name}(" + ", ".join(args) + f") {returns} {{")
    expr = render_path_expression(path)
    if queries:
        lines.append(f"\trequestPath := {expr}")
        lines.append("\tquery := url.Values{}")
        lines.append("\tfor _, values := range queries { for key, entries := range values { query[key] = append(query[key], entries...) } }")
        if sse and any(p.get("name") == "afterSequence" for p in queries):
            lines.append('\tif query.Get("afterSequence") == "" { if lastEventId == "" { query.Set("afterSequence", "0") } else { query.Set("afterSequence", lastEventId) } }')
        elif sse and any(p.get("name") == "lastEventId" for p in queries):
            lines.append('\tif query.Get("lastEventId") == "" && lastEventId != "" { query.Set("lastEventId", lastEventId) }')
        for p in queries:
            default = p.get("schema", {}).get("default")
            if default is not None:
                lines.append(f'\tif query.Get({go_string(p["name"])}) == "" {{ query.Set({go_string(p["name"])}, {go_string(str(default))}) }}')
        lines.append('\tif encoded := query.Encode(); encoded != "" { requestPath += "?" + encoded }')
        expr = "requestPath"
    if sse:
        header = "lastEventId" if last_header else '""'
        lines.append(f"\treader, err := c.sse(ctx, http.Method{method.title()}, {expr}, {header})")
        lines.append("\tif err != nil { return nil, err }")
        adapter = "eventEnvelopeStream{r: reader}" if sse == "envelope" else "modelEventStream{r: reader}"
        lines.append(f"\treturn {adapter}, nil")
    else:
        if idempotency:
            lines.append('\tif idempotencyKey == "" { return nil, platform.NewError(platform.CodeValidation, false, "缺少幂等键") }')
        body_arg = "body" if has_body else "nil"
        key = "idempotencyKey" if idempotency else '""'
        lines.append(f"\treturn c.do(ctx, http.Method{method.title()}, {expr}, {body_arg}, {key})")
    lines.append("}")
    return "\n".join(lines)


def render_clients(slug, impl, producer_specs):
    """生成本域clients.gen.go内容。"""
    needed = needed_operations(impl)
    lines = [CLIENTS_HEAD]
    for producer, ops in needed.items():
        if producer not in producer_specs:
            raise SystemExit(f"{slug}: 生产方规格缺失 {producer}")
        index = operation_index(producer_specs[producer])
        struct = "".join(part.title() for part in producer.split("-"))
        lines.append(f"// {struct}Client 调用{producer}服务（自动附服务断言）。")
        lines.append(f"type {struct}Client struct{{ *producerClient }}")
        lines.append("")
        lines.append(f"func New{struct}Client(baseURL, issuer string, key platform.SigningKey) *{struct}Client {{")
        lines.append(f"\treturn &{struct}Client{{newProducerClient({json.dumps(producer)}, baseURL, issuer, key)}}")
        lines.append("}")
        lines.append("")
        for oid in ops:
            if oid not in index:
                raise SystemExit(f"{slug}: 生产方{producer}缺少operation {oid}")
            method, path, op = index[oid]
            lines.append(render_operation(struct, producer, oid, method, path, op))
            lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-ts", action="store_true", help="跳过openapi-typescript（无node环境时）")
    args = parser.parse_args()

    catalog = load(ROOT / "contracts/modules.json")
    modules = catalog["modules"]
    producer_specs = {m["slug"]: bundle_spec(ROOT / m["root"] / "contracts/openapi.json") for m in modules}

    generated = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for module in modules:
            slug = module["root"].split("/")[-1]
            impl = load(ROOT / module["root"] / "contracts/implementation.json")
            spec = producer_specs[slug]
            registered = {Path(f["path"]).name: f["path"] for f in impl["files"] if "/gen/" in f["path"]}
            gen_dir = ROOT / module["root"] / "internal" / "gen"
            gen_dir.mkdir(parents=True, exist_ok=True)
            # 服务端：oapi-codegen
            if "openapi.gen.go" in registered:
                spec_file = tmp / f"{slug}-openapi.json"
                spec_file.write_text(dump(downgrade_to_30(spec)), encoding="utf-8")
                yaml = (
                    "package: gen\n"
                    "output: internal/gen/openapi.gen.go\n"
                    "generate:\n"
                    "  models: true\n"
                    "  std-http-server: true\n"
                    "  strict-server: true\n"
                    "  embedded-spec: true\n"
                )
                (gen_dir / "oapi-codegen.yaml").write_text(yaml, encoding="utf-8")
                subprocess.run(
                    ["go", "run", OAPI_CODEGEN, "--config", "internal/gen/oapi-codegen.yaml", str(spec_file)],
                    cwd=ROOT / module["root"], check=True)
                generated.append(str(gen_dir / "openapi.gen.go"))
            # 客户端：确定性模板
            if "clients.gen.go" in registered:
                clients_file = gen_dir / "clients.gen.go"
                clients_file.write_text(render_clients(slug, impl, producer_specs), encoding="utf-8")
                subprocess.run(["gofmt", "-w", str(clients_file)], check=True)
                generated.append(str(clients_file))
            # 浏览器类型
            ts_registered = [f["path"] for f in impl["files"] if f["path"].endswith("api.gen.ts")]
            if ts_registered and not args.skip_ts:
                out = ROOT / ts_registered[0]
                out.parent.mkdir(parents=True, exist_ok=True)
                spec_file = tmp / f"{slug}-browser.json"
                spec_file.write_text(dump(spec), encoding="utf-8")
                subprocess.run(["pnpm", "dlx", OPENAPI_TYPESCRIPT, str(spec_file), "-o", str(out)], check=True)
                generated.append(str(out))
    generated += gen_jobs_catalog(modules)
    generated += gen_go_registries(modules)
    generated += gen_portal_routes(modules)
    print("已生成：")
    for path in sorted(generated):
        print(" ", path)


def gen_jobs_catalog(modules):
    """jobs任务类型目录与事件订阅目录。"""
    job_types, subscriptions = [], []
    for module in modules:
        impl = load(ROOT / module["root"] / "contracts/implementation.json")
        for job in impl.get("jobTypes", []):
            job_types.append({
                "type": job["type"], "owner": module["slug"],
                "executor": job["executor"], "schedule": job.get("schedule"),
                "managementPermission": job["managementPermission"],
            })
        events = load(ROOT / module["root"] / "contracts/events.json")
        for event in events.get("events", []):
            if event.get("direction") == "consume":
                subscriptions.append({
                    "event": event["name"], "version": event["version"],
                    "consumer": module["slug"], "handler": event["handler"],
                })
    job_types.sort(key=lambda item: item["type"])
    subscriptions.sort(key=lambda item: (item["event"], item["version"], item["consumer"]))
    jobs_dir = ROOT / "modules/jobs/config"
    jobs_dir.mkdir(parents=True, exist_ok=True)
    (jobs_dir / "job-types.json").write_text(dump({"version": 1, "jobTypes": job_types}), encoding="utf-8")
    (jobs_dir / "event-subscriptions.json").write_text(dump({"version": 1, "subscriptions": subscriptions}), encoding="utf-8")
    return [str(jobs_dir / "job-types.json"), str(jobs_dir / "event-subscriptions.json")]


GO_REGISTRY_HEAD = '''// Code generated by make gen from contracts; DO NOT EDIT.
// {purpose}

package gen

'''


def go_string(value):
    return json.dumps(value, ensure_ascii=False)


def go_string_list(values, indent="\t"):
    if not values:
        return "[]string{}"
    return "[]string{\n" + "".join(f"{indent}\t{go_string(v)},\n" for v in values) + indent + "}"


def gen_go_registries(modules):
    """把运行时必须严格遵守的合同目录生成为Go表，避免手写副本漂移。

    - jobs internal/gen/job_types.gen.go：与config/job-types.json同源的任务类型目录；
    - identity internal/gen/permission_groups.gen.go：根contracts/permission-groups.json的固定映射。
    只有模块implementation.json登记了对应生成文件时才写出。
    """
    roots = {m["slug"]: ROOT / m["root"] for m in modules}
    written = []

    def registered(slug, name):
        impl = load(roots[slug] / "contracts/implementation.json")
        return any(f["path"].endswith("/internal/gen/" + name) for f in impl["files"])

    if "jobs" in roots and registered("jobs", "job_types.gen.go"):
        catalog = load(roots["jobs"] / "config/job-types.json")
        lines = [GO_REGISTRY_HEAD.format(purpose="任务类型目录：由全部模块implementation.json的jobTypes生成，与config/job-types.json同源。")]
        lines.append("// JobTypeEntry 是一个已登记任务类型；Schedule为空表示无系统默认定时。\n")
        lines.append("type JobTypeEntry struct {\n\tType     string\n\tOwner    string\n\tExecutor string\n\tSchedule string\n\tManagementPermission string\n}\n\n")
        lines.append("// JobTypes 按类型排序的全部已登记任务类型。\n")
        lines.append("var JobTypes = []JobTypeEntry{\n")
        for job in catalog["jobTypes"]:
            lines.append(
                f"\t{{Type: {go_string(job['type'])}, Owner: {go_string(job['owner'])}, "
                f"Executor: {go_string(job['executor'])}, Schedule: {go_string(job.get('schedule') or '')}, "
                f"ManagementPermission: {go_string(job['managementPermission'])}}},\n")
        lines.append("}\n\n")
        lines.append("// EventTypeEntry 来自唯一producer与订阅合同；Document自包含，不联网解析schema。\n")
        lines.append("type EventTypeEntry struct {\n Name string\n Version int\n Producer string\n ManagementPermission string\n Consumers []string\n SchemaName string\n Document []byte\n}\n\n")
        groups = load(ROOT / "contracts/permission-groups.json")
        subscriptions = load(roots["jobs"] / "config/event-subscriptions.json")["subscriptions"]
        event_rows = []
        for module in modules:
            source = ROOT / module["root"] / "contracts/events.json"
            for event in load(source)["events"]:
                if event["direction"] != "publish":
                    continue
                schema_doc = {"openapi":"3.1.0","info":{"title":"事件载荷","version":"1"},"paths":{},"components":{"schemas":{"Payload":event["payloadSchema"]}}}
                schema_doc = downgrade_to_30(bundle_spec(source, schema_doc))
                consumers = sorted({row["consumer"] for row in subscriptions if row["event"] == event["name"] and row["version"] == event["version"]})
                event_rows.append((event["name"], event["version"], module["slug"], consumers, schema_doc))
        lines.append("var EventTypes = []EventTypeEntry{\n")
        for name,version,producer,consumers,document in sorted(event_rows, key=lambda row:(row[0],row[1])):
            permission = groups["eventManagementPermissions"][producer]
            payload = json.dumps(document,ensure_ascii=False,separators=(",",":"),sort_keys=True)
            lines.append(f"{{Name:{go_string(name)},Version:{version},Producer:{go_string(producer)},ManagementPermission:{go_string(permission)},Consumers:{go_string_list(consumers)},SchemaName:\"Payload\",Document:[]byte({go_string(payload)})}},\n")
        lines.append("}\n")
        out = roots["jobs"] / "internal/gen/job_types.gen.go"
        out.write_text("".join(lines), encoding="utf-8")
        subprocess.run(["gofmt", "-w", str(out)], check=True)
        written.append(str(out))

    if "identity" in roots and registered("identity", "permission_groups.gen.go"):
        groups = load(ROOT / "contracts/permission-groups.json")
        lines = [GO_REGISTRY_HEAD.format(purpose="功能开关到技术权限的固定映射：由根contracts/permission-groups.json生成。")]
        lines.append(f"// PermissionGroupsVersion 是映射合同版本。\nconst PermissionGroupsVersion = {int(groups['version'])}\n\n")
        lines.append("// DefaultSelectedPermissions 是未指定时默认全选的功能开关，按合同顺序。\n")
        lines.append("var DefaultSelectedPermissions = " + go_string_list(groups["defaultSelected"], "") + "\n\n")
        lines.append("// PermissionGroups 是每个功能开关派生的技术权限。\n")
        lines.append("var PermissionGroups = map[string][]string{\n")
        for name in sorted(groups["groups"]):
            lines.append(f"\t{go_string(name)}: " + go_string_list(groups["groups"][name]) + ",\n")
        lines.append("}\n\n")
        lines.append("// AuthenticatedBaseGrants 是所有已登录账户固定拥有的基础权限。\n")
        lines.append("var AuthenticatedBaseGrants = " + go_string_list(groups["authenticatedBaseGrants"], "") + "\n\n")
        lines.append("// SuperadminOnlyGrants 只授予唯一超管，子账号不得获得。\n")
        lines.append("var SuperadminOnlyGrants = " + go_string_list(groups["superadminOnly"], "") + "\n\n")
        lines.append("// JobManagementGrants 派生入口粗能力；任务服务仍按持久类型核业务权限。\n")
        lines.append("var JobManagementGrants = " + go_string_list(groups["jobManagementGrants"], "") + "\n")
        out = roots["identity"] / "internal/gen/permission_groups.gen.go"
        out.write_text("".join(lines), encoding="utf-8")
        subprocess.run(["gofmt", "-w", str(out)], check=True)
        written.append(str(out))
    return written


def gen_portal_routes(modules):
    """portal入口路由表：非service接口的方法/路径到归属与标志。"""
    routes = []
    for module in modules:
        spec = bundle_spec(ROOT / module["root"] / "contracts/openapi.json")
        for path, methods in spec.get("paths", {}).items():
            for method, op in methods.items():
                if method.lower() not in METHODS or not isinstance(op, dict):
                    continue
                permission = op.get("x-permission", "")
                if permission == "service":
                    continue
                streaming = any(
                    "text/event-stream" in (content or {})
                    for response in op.get("responses", {}).values()
                    for content in [response.get("content", {})]
                )
                routes.append({
                    "method": method.upper(), "path": path, "owner": module["slug"],
                    "operationId": op.get("operationId", ""), "permission": permission,
                    "admission": op.get("x-admission"),
                    "timeoutMs": op.get("x-timeout-ms"), "streaming": streaming,
                })
    routes.sort(key=lambda item: (item["path"], item["method"]))
    portal_dir = ROOT / "modules/portal/config"
    portal_dir.mkdir(parents=True, exist_ok=True)
    (portal_dir / "routes.json").write_text(dump({"version": 1, "routes": routes}), encoding="utf-8")
    return [str(portal_dir / "routes.json")]


